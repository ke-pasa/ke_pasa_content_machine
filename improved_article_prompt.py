def get_improved_prompt(title, content):
    """Генерирует улучшенный промпт для создания статьи"""
    return IMPROVED_ARTICLE_PROMPT.format(
        title=title,
        content=content
    )

def validate_article_quality(article_data):
    """
    Валидирует качество сгенерированной статьи
    Возвращает оценку и рекомендации по улучшению
    """
    title = article_data.get('title', '')
    content = article_data.get('content', '')
    category = article_data.get('category', 'general')
    
    if not title or not content:
        return {
            'score': 0,
            'level': 'критическое',
            'issues': ['Отсутствует заголовок или контент'],
            'recommendations': ['Проверить данные статьи']
        }
    
    # Подсчитываем слова (примерно)
    word_count = len(content.split())
    char_count = len(content)
    
    # Проверяем наличие подзаголовков
    has_subheadings = '## ' in content or '### ' in content
    
    # Проверяем наличие цифр
    has_numbers = any(char.isdigit() for char in content)
    
    # Проверяем наличие общих фраз
    generic_phrases = [
        "жара в испании", "лесные пожары", "погода в испании",
        "что происходит", "как справиться", "что нас ждет",
        "ситуация в испании", "проблемы испании"
    ]
    
    generic_count = sum(1 for phrase in generic_phrases if phrase in content.lower())
    
    # Проверяем категорию
    good_category = category != 'general'
    
    # Проверяем конкретику (наличие цифр, дат, имен)
    has_specific_content = has_numbers and ('€' in content or 'евро' in content or '2025' in content)
    
    # Оценка качества
    score = 0
    issues = []
    recommendations = []
    
    # Проверка длины
    if 600 <= word_count <= 800:
        score += 2
    elif 500 <= word_count <= 900:
        score += 1
        issues.append("Длина статьи не оптимальна")
        recommendations.append("Оптимизировать длину до 600-800 слов")
    else:
        issues.append("Статья слишком длинная или короткая")
        recommendations.append("Привести длину к 600-800 словам")
    
    # Проверка структуры
    if has_subheadings:
        score += 1
    else:
        issues.append("Отсутствуют подзаголовки")
        recommendations.append("Добавить подзаголовки для структурирования")
    
    # Проверка конкретики
    if has_numbers:
        score += 1
    else:
        issues.append("Отсутствуют цифры")
        recommendations.append("Включить конкретные цифры и даты")
    
    # Проверка общих фраз
    if generic_count <= 1:
        score += 1
    else:
        issues.append(f"Слишком много общих фраз ({generic_count})")
        recommendations.append("Заменить общие фразы на конкретику")
    
    # Проверка категории
    if good_category:
        score += 1
    else:
        issues.append("Категория 'general' - нужна более специфичная")
        recommendations.append("Определить правильную категорию на основе содержания")
    
    # Проверка конкретики контента
    if has_specific_content:
        score += 1
    else:
        issues.append("Недостаточно конкретики в контенте")
        recommendations.append("Добавить больше конкретных фактов, цифр, имен")
    
    # Определяем уровень качества
    if score >= 6:
        level = "высокое"
    elif score >= 4:
        level = "среднее"
    else:
        level = "низкое"
    
    return {
        'score': score,
        'level': level,
        'issues': issues,
        'recommendations': recommendations,
        'word_count': word_count,
        'char_count': char_count,
        'has_subheadings': has_subheadings,
        'has_numbers': has_numbers,
        'generic_phrases_count': generic_count,
        'good_category': good_category,
        'category': category,
        'has_specific_content': has_specific_content
    }

def format_article_structure(content):
    """
    Форматирует структуру статьи для лучшей читаемости
    """
    # Разбиваем на абзацы
    paragraphs = content.split('\n\n')
    
    # Добавляем подзаголовки если их нет
    if '## ' not in content and len(paragraphs) > 3:
        formatted_content = []
        formatted_content.append(paragraphs[0])  # Введение
        
        # Добавляем подзаголовки для основных разделов
        for i, para in enumerate(paragraphs[1:-1], 1):
            if i == 1:
                formatted_content.append(f"\n## Основные детали\n{para}")
            elif i == 2:
                formatted_content.append(f"\n## Дополнительная информация\n{para}")
            else:
                formatted_content.append(f"\n## Детали и последствия\n{para}")
        
        formatted_content.append(f"\n## Заключение\n{paragraphs[-1]}")
        
        return '\n\n'.join(formatted_content)
    
    return content
