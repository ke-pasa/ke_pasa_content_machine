#!/usr/bin/env python3
"""
Тест отправки длинного поста с изображением (>1024 символов)
"""

import os
import sys

# Добавляем корневую директорию в путь
current_dir = os.path.dirname(os.path.abspath(__file__))
parent_dir = os.path.dirname(current_dir)
sys.path.insert(0, parent_dir)

from rss_parser import RSSParser, load_env_file

def test_long_post_with_image():
    """Тестирует отправку длинного поста с изображением"""
    
    # Загружаем переменные окружения
    load_env_file()
    
    # Проверяем наличие токенов
    bot_token = os.environ.get('TELEGRAM_BOT_TOKEN')
    chat_id = os.environ.get('TELEGRAM_CHAT_ID')
    
    if not bot_token or not chat_id:
        print("❌ Не найдены TELEGRAM_BOT_TOKEN или TELEGRAM_CHAT_ID")
        return
    
    print("🧪 Тест длинного поста с изображением (>1024 символов)")
    print("=" * 60)
    
    rss_parser = RSSParser()
    
    # Создаем длинный пост, который точно превышает 1024 символа
    long_post = """🧲 Важные изменения в системе здравоохранения Испании

🧾 Министерство здравоохранения Испании (Ministerio de Sanidad) объявило о масштабных изменениях в системе медицинского обслуживания, которые затронут всех жителей страны, включая иностранных граждан.

Основные изменения включают:

🏥 **Новая система записи к врачу**
- Внедрение единой цифровой платформы для записи на прием
- Возможность онлайн-консультаций через приложение
- Упрощенная система получения рецептов

💊 **Изменения в системе лекарственного обеспечения**
- Расширенный список бесплатных лекарств
- Новые льготы для пенсионеров и людей с хроническими заболеваниями
- Улучшенная система доставки лекарств на дом

🏛️ **Реформа медицинских центров**
- Модернизация оборудования в государственных клиниках
- Увеличение количества специалистов
- Сокращение времени ожидания приема

📋 **Новые требования для иностранных граждан**
- Обновленные правила получения медицинской карты (Tarjeta Sanitaria)
- Упрощенная процедура регистрации в системе здравоохранения
- Дополнительные услуги для недавно прибывших мигрантов

Эти изменения направлены на улучшение качества медицинского обслуживания и повышение доступности медицинских услуг для всех жителей Испании. Ожидается, что реформа будет полностью внедрена в течение следующих 18 месяцев.

🔗 Ссылка на полную статью: https://example.com/healthcare-reform/

💬 Как эти изменения повлияют на ваше медицинское обслуживание? Поделитесь своим опытом в комментариях!"""
    
    test_article = {
        'title': 'Важные изменения в системе здравоохранения Испании',
        'telegram_post': long_post,
        'image': 'https://picsum.photos/800/600',
        'slug': 'healthcare-reform'
    }
    
    print(f"📏 Длина поста: {len(long_post)} символов")
    print(f"🖼️  Изображение: https://picsum.photos/800/600")
    print(f"📊 Превышает лимит 1024 символа: {'Да' if len(long_post) > 1024 else 'Нет'}")
    
    print("\n🚀 Отправляем пост...")
    result = rss_parser.send_telegram_post(test_article)
    
    if result:
        print("✅ Пост успешно отправлен!")
        print("\n📋 Ожидаемое поведение:")
        print("1. Изображение отправлено отдельно (без подписи)")
        print("2. Полный текст поста отправлен отдельным сообщением")
        print("3. Никакая информация не потеряна")
    else:
        print("❌ Ошибка при отправке поста")

if __name__ == "__main__":
    test_long_post_with_image() 