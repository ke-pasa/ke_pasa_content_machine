#!/usr/bin/env python3
"""
Тест новой логики обработки длинных постов и изображений в Telegram
"""

import os
import sys

# Добавляем корневую директорию в путь
current_dir = os.path.dirname(os.path.abspath(__file__))
parent_dir = os.path.dirname(current_dir)
sys.path.insert(0, parent_dir)

from rss_parser import RSSParser, load_env_file

def test_telegram_limits():
    """Тестирует различные сценарии отправки постов в Telegram"""
    
    # Загружаем переменные окружения
    load_env_file()
    
    # Проверяем наличие токенов
    bot_token = os.environ.get('TELEGRAM_BOT_TOKEN')
    chat_id = os.environ.get('TELEGRAM_CHAT_ID')
    
    if not bot_token or not chat_id:
        print("❌ Не найдены TELEGRAM_BOT_TOKEN или TELEGRAM_CHAT_ID")
        return
    
    print("🧪 Тестирование новой логики отправки Telegram-постов")
    print("=" * 60)
    
    rss_parser = RSSParser()
    
    # Тест 1: Короткий пост с изображением (должен отправиться с подписью)
    print("\n1️⃣ Тест 1: Короткий пост с изображением")
    print("-" * 40)
    
    short_post = """🧲 Тест короткого поста

🧾 Это короткий пост длиной менее 1024 символов, который должен отправиться с изображением и подписью.

🔗 Ссылка: https://example.com/test/

💬 Что думаете об этом тесте?"""
    
    test_article_1 = {
        'title': 'Тест короткого поста',
        'telegram_post': short_post,
        'image': 'https://picsum.photos/800/600',
        'slug': 'test-short'
    }
    
    print(f"📏 Длина поста: {len(short_post)} символов")
    print("🖼️  Изображение: https://picsum.photos/800/600")
    
    result = rss_parser.send_telegram_post(test_article_1)
    print(f"✅ Результат: {'Успешно' if result else 'Ошибка'}")
    
    # Тест 2: Длинный пост с изображением (должен отправиться раздельно)
    print("\n2️⃣ Тест 2: Длинный пост с изображением")
    print("-" * 40)
    
    long_post = """🧲 Тест длинного поста с изображением

🧾 Это длинный пост, который превышает лимит в 1024 символа для подписи к изображению. Такой пост должен быть отправлен следующим образом: сначала изображение без подписи, а затем полный текст поста отдельным сообщением.

Это позволяет сохранить и изображение, и полный текст поста, не теряя никакой информации. Стратегия работает следующим образом:

1. Проверяется длина поста
2. Если пост длиннее 1024 символов, изображение отправляется отдельно
3. Затем отправляется полный текст поста
4. Если изображение не удается отправить, отправляется только текст

🔗 Ссылка: https://example.com/test-long/

💬 Как вам такая стратегия отправки длинных постов?"""
    
    test_article_2 = {
        'title': 'Тест длинного поста',
        'telegram_post': long_post,
        'image': 'https://picsum.photos/800/600',
        'slug': 'test-long'
    }
    
    print(f"📏 Длина поста: {len(long_post)} символов")
    print("🖼️  Изображение: https://picsum.photos/800/600")
    
    result = rss_parser.send_telegram_post(test_article_2)
    print(f"✅ Результат: {'Успешно' if result else 'Ошибка'}")
    
    # Тест 3: Очень длинный пост без изображения (должен разбиться на части)
    print("\n3️⃣ Тест 3: Очень длинный пост без изображения")
    print("-" * 40)
    
    very_long_post = """🧲 Тест очень длинного поста

🧾 Это очень длинный пост, который превышает лимит Telegram в 4096 символов для одного сообщения. Такой пост должен быть автоматически разбит на несколько частей с сохранением целостности абзацев.

Система работает следующим образом:

1. Проверяется общая длина поста
2. Если пост длиннее 4096 символов, он разбивается на части по 4000 символов
3. Разбивка происходит по абзацам, чтобы сохранить читаемость
4. Каждая часть отправляется отдельным сообщением

Это особенно полезно для длинных аналитических статей или подробных обзоров, где важно сохранить весь контент.

Примеры ситуаций, когда это может понадобиться:
- Подробные анализы политических событий
- Длинные интервью с важными фигурами
- Детальные обзоры изменений в законодательстве
- Комплексные материалы о социальных проблемах

В таких случаях важно не терять информацию, но при этом сохранять удобство чтения.

🔗 Ссылка: https://example.com/test-very-long/

💬 Как вам такая система разбивки длинных постов на части?"""
    
    test_article_3 = {
        'title': 'Тест очень длинного поста',
        'telegram_post': very_long_post,
        'slug': 'test-very-long'
    }
    
    print(f"📏 Длина поста: {len(very_long_post)} символов")
    print("🖼️  Изображение: нет")
    
    result = rss_parser.send_telegram_post(test_article_3)
    print(f"✅ Результат: {'Успешно' if result else 'Ошибка'}")
    
    # Тест 4: Обычный пост без изображения
    print("\n4️⃣ Тест 4: Обычный пост без изображения")
    print("-" * 40)
    
    normal_post = """🧲 Обычный пост без изображения

🧾 Это обычный пост средней длины без изображения. Он должен отправиться как обычное текстовое сообщение с поддержкой Markdown-разметки.

🔗 Ссылка: https://example.com/test-normal/

💬 Все работает как ожидается?"""
    
    test_article_4 = {
        'title': 'Обычный пост',
        'telegram_post': normal_post,
        'slug': 'test-normal'
    }
    
    print(f"📏 Длина поста: {len(normal_post)} символов")
    print("🖼️  Изображение: нет")
    
    result = rss_parser.send_telegram_post(test_article_4)
    print(f"✅ Результат: {'Успешно' if result else 'Ошибка'}")
    
    print("\n🎉 Тестирование завершено!")

if __name__ == "__main__":
    test_telegram_limits() 