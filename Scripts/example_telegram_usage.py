#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
Пример использования функции генерации Telegram-поста
"""

from rss_parser import RSSParser

def main():
    """Пример использования функции generate_telegram_post"""
    
    # Создаем экземпляр парсера
    parser = RSSParser()
    
    # Пример статьи (после обработки через process_article)
    article = {
        "title": "Новые правила аренды жилья в Испании с 2025 года",
        "description": "Испанское правительство вводит новые правила аренды недвижимости, которые защитят права арендаторов и упростят процесс поиска жилья.",
        "content": """
        Министерство транспорта, мобильности и городской повестки Испании объявило о введении новых правил аренды недвижимости, которые вступят в силу с 1 марта 2025 года. Изменения направлены на защиту прав арендаторов и упрощение процесса поиска жилья.

        Основные нововведения включают:
        - Ограничение максимального залога до 2 месяцев аренды
        - Запрет на требование поручителей для арендаторов с подтвержденным доходом
        - Упрощение процедуры расторжения договора аренды
        - Обязательное включение коммунальных услуг в стоимость аренды
        - Новые требования к энергоэффективности арендуемого жилья

        По словам министра, новые правила помогут решить проблему доступности жилья для мигрантов и молодых семей. Особенно это касается крупных городов, где цены на аренду значительно выросли за последние годы.

        Эксперты отмечают, что изменения могут повлиять на рынок недвижимости и сделать аренду более доступной для иностранцев, включая русскоязычных мигрантов.
        """,
        "tags": ["аренда", "недвижимость", "Испания", "2025", "новые правила"],
        "slug": "new-rental-rules-2025"
    }
    
    print("📰 Пример статьи:")
    print(f"   Заголовок: {article['title']}")
    print(f"   Теги: {', '.join(article['tags'])}")
    print()
    
    # Генерируем Telegram-пост
    print("📱 Генерация Telegram-поста...")
    telegram_post = parser.generate_telegram_post(article)
    
    print(f"✅ Пост сгенерирован ({len(telegram_post)} символов)")
    print()
    print("📱 СГЕНЕРИРОВАННЫЙ ПОСТ:")
    print("=" * 50)
    print(telegram_post)
    print("=" * 50)
    
    # Пример отправки в Telegram (закомментирован)
    print()
    print("📤 Для отправки в Telegram используйте:")
    print("""
    import telegram
    
    bot = telegram.Bot(token='YOUR_BOT_TOKEN')
    bot.send_message(
        chat_id='@your_channel',
        text=telegram_post,
        parse_mode='Markdown'
    )
    """)

if __name__ == "__main__":
    main() 