def get_enhanced_prompt_v4(title, content):
    """Возвращает промпт версии 4.0 для генерации статьи"""
    return ENHANCED_ARTICLE_PROMPT_V4.format(title=title, content=content)

def validate_enhanced_article_v4(article_data):
    """
    Валидирует статью по новым стандартам версии 4.0
    """
    title = article_data.get('title', '')
    content = article_data.get('content', '')
    category = article_data.get('category', '')
    
    # Базовые проверки
    word_count = len(content.split())
    has_subheadings = '## ' in content
    good_category = category != 'general'
    
    # Проверяем конкретику
    has_numbers = any(char.isdigit() for char in content)
    has_places = any(word in content.lower() for word in ['мадрид', 'барселона', 'валенсия', 'севилья', 'бильбао'])
    
    # Проверяем акцент на мигрантах
    migrant_focus = content.lower().count('русскоязычн') + content.lower().count('мигрант')
    
    # Проверяем корявые переводы
    bad_translations = content.lower().count('полиция национальная') + content.lower().count('полиция региональная')
    
    # НОВЫЕ ПРОВЕРКИ ВЕРСИИ 4.0
    has_emotional_title = any(word in title.lower() for word in ['драма', 'буря', 'шок', 'кризис', 'катастрофа', 'трагедия'])
    has_hook_intro = any(phrase in content.lower() for phrase in ['представьте себе', 'вообразите', 'что если', 'представьте, что'])
    has_short_paragraphs = content.count('\n\n') >= 8  # Минимум 8 двойных переносов строк
    has_active_verbs = any(verb in content.lower() for verb in ['уничтожил', 'провел', 'изменил', 'создал', 'построил'])
    has_quotes = content.count('"') >= 4  # Минимум 2 цитаты
    has_concrete_names = any(name in content for name in ['Мария', 'Карлос', 'Анна', 'Гонсало', 'Елена'])
    has_comparisons = any(phrase in content.lower() for phrase in ['это как', 'это похоже на', 'представьте, что'])
    has_questions = any(char in content for char in ['?'])
    has_calls_to_action = any(phrase in content.lower() for phrase in ['будьте', 'помогайте', 'участвуйте', 'следите'])
    has_emojis = any(char in content for char in ['🔥', '🚔', '💰', '🚨', '📞', '🌡️', '💸', '🌍', '🔮', '💪'])
    
    # Оценка качества по новым стандартам версии 4.0
    score = 0
    issues = []
    recommendations = []
    
    # Базовые проверки (5 баллов)
    if word_count >= 800:
        score += 1
    else:
        issues.append("Статья слишком короткая")
        recommendations.append("Увеличить до минимум 800 слов")
    
    if has_subheadings:
        score += 1
    else:
        issues.append("Отсутствуют подзаголовки")
        recommendations.append("Добавить подзаголовки H2")
    
    if good_category:
        score += 1
    else:
        issues.append("Категория 'general'")
        recommendations.append("Изменить на конкретную категорию")
    
    if has_numbers and ('€' in content or 'евро' in content or '2025' in content):
        score += 1
    else:
        issues.append("Недостаточно конкретики в контенте")
        recommendations.append("Добавить больше конкретных фактов, цифр, имен")
    
    if has_places:
        score += 1
    else:
        issues.append("Недостаточно конкретных мест")
        recommendations.append("Добавить названия городов, районов, улиц")
    
    # Проверка акцента на мигрантах
    if migrant_focus == 0:
        score += 1
    else:
        issues.append(f"Слишком много акцента на мигрантах ({migrant_focus})")
        recommendations.append("Убрать акцент на 'русскоязычных мигрантах'")
    
    # Проверка корявых переводов
    if bad_translations == 0:
        score += 1
    else:
        issues.append(f"Обнаружены корявые переводы ({bad_translations})")
        recommendations.append("Исправить корявые переводы на естественный русский язык")
    
    # НОВЫЕ ПРОВЕРКИ ВЕРСИИ 4.0 (7 баллов)
    if has_emotional_title:
        score += 1
    else:
        issues.append("Заголовок недостаточно эмоциональный")
        recommendations.append("Сделать заголовок более эмоциональным и привлекательным")
    
    if has_hook_intro:
        score += 1
    else:
        issues.append("Отсутствует вступление-крючок")
        recommendations.append("Добавить вступление с 'Представьте себе...' или 'Вообразите...'")
    
    if has_short_paragraphs:
        score += 1
    else:
        issues.append("Абзацы слишком длинные")
        recommendations.append("Разбить длинные абзацы на короткие (2-3 предложения)")
    
    if has_active_verbs:
        score += 1
    else:
        issues.append("Недостаточно активных глаголов")
        recommendations.append("Заменить пассивные конструкции на активные")
    
    if has_quotes:
        score += 1
    else:
        issues.append("Отсутствуют цитаты участников")
        recommendations.append("Добавить цитаты реальных людей")
    
    if has_concrete_names:
        score += 1
    else:
        issues.append("Недостаточно конкретных имен")
        recommendations.append("Добавить имена участников событий, специалистов, должностных лиц")
    
    if has_comparisons:
        score += 1
    else:
        issues.append("Отсутствуют сравнения и аналогии")
        recommendations.append("Добавить сравнения типа 'Это как...', 'Это похоже на...'")
    
    if has_questions:
        score += 1
    else:
        issues.append("Отсутствуют вопросы к читателю")
        recommendations.append("Добавить вопросы для вовлечения читателя")
    
    if has_calls_to_action:
        score += 1
    else:
        issues.append("Отсутствуют призывы к действию")
        recommendations.append("Добавить призывы типа 'Будьте бдительны', 'Помогайте соседям'")
    
    if has_emojis:
        score += 1
    else:
        issues.append("Отсутствуют эмодзи")
        recommendations.append("Добавить эмодзи в подзаголовки для визуального разделения")
    
    # Определяем уровень качества
    if score >= 17:
        level = "высокое"
    elif score >= 14:
        level = "среднее"
    else:
        level = "низкое"
    
    return {
        'score': score,
        'level': level,
        'word_count': word_count,
        'has_subheadings': has_subheadings,
        'good_category': good_category,
        'category': category,
        'has_specific_content': has_numbers and ('€' in content or 'евро' in content or '2025' in content),
        'migrant_focus_count': migrant_focus,
        'bad_translations_count': bad_translations,
        'issues': issues,
        'recommendations': recommendations,
        # Новые проверки версии 4.0
        'has_emotional_title': has_emotional_title,
        'has_hook_intro': has_hook_intro,
        'has_short_paragraphs': has_short_paragraphs,
        'has_active_verbs': has_active_verbs,
        'has_quotes': has_quotes,
        'has_concrete_names': has_concrete_names,
        'has_comparisons': has_comparisons,
        'has_questions': has_questions,
        'has_calls_to_action': has_calls_to_action,
        'has_emojis': has_emojis
    }

