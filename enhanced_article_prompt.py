def get_enhanced_prompt(title, content):
    """Генерирует улучшенный промпт для создания статьи"""
    return ENHANCED_ARTICLE_PROMPT.format(
        title=title,
        content=content
    )

def validate_enhanced_article(article_data):
    """
    Валидирует качество статьи по новым стандартам
    """
    title = article_data.get('title', '')
    content = article_data.get('content', '')
    category = article_data.get('category', 'general')
    
    if not title or not content:
        return {
            'score': 0,
            'level': 'критическое',
            'issues': ['Отсутствует заголовок или контент'],
            'recommendations': ['Проверить данные статьи']
        }
    
    # Подсчитываем слова
    word_count = len(content.split())
    char_count = len(content)
    
    # Проверяем наличие подзаголовков
    has_subheadings = '## ' in content
    
    # Проверяем наличие цифр
    has_numbers = any(char.isdigit() for char in content)
    
    # Проверяем наличие общих фраз
    generic_phrases = [
        "жара в испании", "лесные пожары", "погода в испании",
        "что происходит", "как справиться", "что нас ждет",
        "ситуация в испании", "проблемы испании"
    ]
    
    generic_count = sum(1 for phrase in generic_phrases if phrase in content.lower())
    
    # Проверяем категорию
    good_category = category != 'general'
    
    # Проверяем конкретику
    has_specific_content = has_numbers and ('€' in content or 'евро' in content or '2025' in content)
    
    # Проверяем акцент на мигрантах
    migrant_focus = content.lower().count('русскоязычн') + content.lower().count('мигрант')
    
    # Проверяем корявые переводы
    bad_translations = content.lower().count('полиция национальная') + content.lower().count('полиция региональная')
    
    # Оценка качества по новым стандартам
    score = 0
    issues = []
    recommendations = []
    
    # Проверка длины (новые стандарты)
    if 800 <= word_count <= 1500:
        score += 2
    elif 600 <= word_count < 800:
        score += 1
        issues.append("Статья короче рекомендуемых 800 слов")
        recommendations.append("Увеличить длину до 800-1500 слов")
    else:
        issues.append("Статья слишком длинная или короткая")
        recommendations.append("Привести длину к 800-1500 словам")
    
    # Проверка структуры
    if has_subheadings:
        score += 2  # Увеличиваем вес подзаголовков
    else:
        issues.append("Отсутствуют подзаголовки")
        recommendations.append("Добавить подзаголовки H2 для каждого раздела")
    
    # Проверка конкретики
    if has_numbers:
        score += 1
    else:
        issues.append("Отсутствуют цифры")
        recommendations.append("Включить конкретные цифры и даты")
    
    # Проверка общих фраз
    if generic_count == 0:
        score += 2  # Увеличиваем вес отсутствия общих фраз
    elif generic_count <= 1:
        score += 1
    else:
        issues.append(f"Слишком много общих фраз ({generic_count})")
        recommendations.append("Заменить все общие фразы на конкретику")
    
    # Проверка категории
    if good_category:
        score += 2  # Увеличиваем вес правильной категории
    else:
        issues.append("Категория 'general' - нужна более специфичная")
        recommendations.append("Определить правильную категорию на основе содержания")
    
    # Проверка конкретики контента
    if has_specific_content:
        score += 1
    else:
        issues.append("Недостаточно конкретики в контенте")
        recommendations.append("Добавить больше конкретных фактов, цифр, имен")
    
    # Проверка акцента на мигрантах
    if migrant_focus == 0:
        score += 2  # Увеличиваем вес отсутствия акцента
    else:
        issues.append(f"Слишком много акцента на мигрантах ({migrant_focus})")
        recommendations.append("Убрать акцент на 'русскоязычных мигрантах'")
    
    # Проверка корявых переводов
    if bad_translations == 0:
        score += 1
    else:
        issues.append(f"Обнаружены корявые переводы ({bad_translations})")
        recommendations.append("Исправить корявые переводы на естественный русский язык")
    
    # Определяем уровень качества
    if score >= 10:
        level = "высокое"
    elif score >= 7:
        level = "среднее"
    else:
        level = "низкое"
    
    return {
        'score': score,
        'level': level,
        'issues': issues,
        'recommendations': recommendations,
        'word_count': word_count,
        'char_count': char_count,
        'has_subheadings': has_subheadings,
        'has_numbers': has_numbers,
        'generic_phrases_count': generic_count,
        'good_category': good_category,
        'category': category,
        'has_specific_content': has_specific_content,
        'migrant_focus_count': migrant_focus,
        'bad_translations_count': bad_translations
    }
