STAGE4_SYSTEM_PROMPT = (
    "Ты — редактор телеграм-канала новостного проекта.\n\n"
    "На вход ты получаешь готовый материал (title, body, url). \n"
    "Твоя задача — написать короткий, живой и профессиональный анонс для публикации в Telegram.\n\n"
    "⚙️ Правила:\n"
    "• Стиль: нейтральный, естественный, без кликбейта и эмоциональных оценок.\n"
    "• Объём — до 600 символов, максимум два коротких абзаца (по 2–3 предложения каждый).\n"
    "• Передавай суть: кто, что, где, когда, почему это важно.\n"
    "• Если это расследование, судебное дело или открытие — сделай акцент на действии и значении.\n"
    "• Не повторяй заголовок дословно.\n"
    "• Избегай громоздких уточнений (даты, названия учреждений и фамилии оставляй только ключевые).\n"
    "• Не используй Markdown, HTML, эмодзи и хэштеги.\n"
    "• Заверши анонс ссылкой на источник в формате: \"Подробнее: {url}\".\n"
    "• Ответ строго в JSON, без пояснений и комментариев."
)

STAGE4_USER_TEMPLATE = (
    "Сделай короткий анонс для Telegram по данным статьи.\n\n"
    "Дано:\n"
    "<<PAYLOAD_JSON>>\n\n"
    "Верни JSON:\n"
    "{\n"
    "  \"tg_preview\": \"один короткий абзац (до 600 символов) с ссылкой в конце\"\n"
    "}"
)


def stage1_messages(article_text: str) -> List[Dict[str, str]]:
    user_content = STAGE1_USER_TEMPLATE.replace("<<ARTICLE_TEXT>>", article_text)
    return [
        {"role": "system", "content": STAGE1_SYSTEM_PROMPT},
        {"role": "user", "content": user_content},
    ]


def stage2_messages(draft_json: str) -> List[Dict[str, str]]:
    user_content = STAGE2_USER_TEMPLATE.replace("<<DRAFT_JSON>>", draft_json)
    return [
        {"role": "system", "content": STAGE2_SYSTEM_PROMPT},
        {"role": "user", "content": user_content},
    ]


def stage3_messages(stage2_json: str, source_line: str) -> List[Dict[str, str]]:
    user_content = (
        STAGE3_USER_TEMPLATE
        .replace("<<STAGE2_JSON>>", stage2_json)
        .replace("<<SOURCE_LINE>>", source_line)
    )
    return [
        {"role": "system", "content": STAGE3_SYSTEM_PROMPT},
        {"role": "user", "content": user_content},
    ]


def stage4_messages(payload_json: str) -> List[Dict[str, str]]:
    user_content = STAGE4_USER_TEMPLATE.replace("<<PAYLOAD_JSON>>", payload_json)
    return [
        {"role": "system", "content": STAGE4_SYSTEM_PROMPT},
        {"role": "user", "content": user_content},
    ]
