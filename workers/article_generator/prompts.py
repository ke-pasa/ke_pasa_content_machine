def stage1_messages(article_text: str) -> List[Dict[str, str]]:
    user_content = STAGE1_USER_TEMPLATE.replace("<<ARTICLE_TEXT>>", article_text)
    return [
        {"role": "system", "content": STAGE1_SYSTEM_PROMPT},
        {"role": "user", "content": user_content},
    ]


