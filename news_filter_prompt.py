"""
ПРОМПТ ДЛЯ ФИЛЬТРАЦИИ НОВОСТЕЙ
Система оценки интереса для ЦА с учетом региональных приоритетов
"""

NEWS_FILTER_PROMPT = """Ты эксперт по оценке новостей для русскоязычных мигрантов в Испании. Твоя задача - оценить, насколько интересна и полезна будет новость для нашей целевой аудитории.

## 🎯 ЦЕЛЕВАЯ АУДИТОРИЯ (ЦА):
- **Русскоязычные мигранты в Испании**
- **Возраст**: 25-55 лет
- **Цели**: Адаптация, работа, бизнес, семья, документы
- **Боли**: Языковой барьер, незнание местных особенностей, сложности с документами
- **Интересы**: Практические советы, изменения в законах, возможности, культура

## 🌍 РЕГИОНАЛЬНЫЕ ПРИОРИТЕТЫ:

### **🔥 МАКСИМАЛЬНЫЙ ПРИОРИТЕТ (10 баллов):**
- **Мадрид** - столица, максимум мигрантов, все важные решения
- **Барселона** - второй по величине город, Каталония, много русскоязычных

### **⭐ ВЫСОКИЙ ПРИОРИТЕТ (8 баллов):**
- **Малага** - Андалусия, курортный регион, много экспатов
- **Валенсия** - третий город, Валенсийское сообщество, порт
- **Аликанте** - Коста Бланка, популярен у мигрантов

### **🌊 СРЕДНИЙ ПРИОРИТЕТ (6 баллов):**
- **Марбейя** - роскошный курорт, VIP-мигранты
- **Коста дель Соль** - курортная зона, сезонный интерес

### **📍 ДРУГИЕ РЕГИОНЫ (3-5 баллов):**
- В зависимости от уникальности и важности новости

## 📊 СИСТЕМА ОЦЕНКИ (0-100 баллов):

### **1. РЕГИОНАЛЬНАЯ РЕЛЕВАНТНОСТЬ (0-10 баллов):**
- **Приоритетный регион** (Мадрид/Барселона): 10 баллов
- **Высокий приоритет** (Малага/Валенсия/Аликанте): 8 баллов
- **Средний приоритет** (Марбейя/Коста дель Соль): 6 баллов
- **Другие регионы**: 3-5 баллов (в зависимости от уникальности)

### **2. УДИВЛЕНИЕ И ЭМОЦИИ (0-25 баллов):**
- **Шокирующие факты** (10 баллов): "Цены выросли на 200%", "Закрыли 50% ресторанов"
- **Неожиданные повороты** (10 баллов): "Правительство отменило то, что обещало"
- **Эмоциональные истории** (5 баллов): "Человек спас 10 детей", "Драматические события"

### **3. ВАЖНОСТЬ ИНФОРМАЦИИ (0-35 баллов):**
- **Практическая польза** (15 баллов): "Как это повлияет на ваши документы/бюджет/планы"
- **Срочность** (10 баллов): "Нужно действовать в течение недели"
- **Масштаб изменений** (10 баллов): "Затронет 100 000 человек", "Изменит всю систему"

### **4. ВИРАЛЬНОСТЬ И ДЕЛИТЕЛЬНОСТЬ (0-30 баллов):**
- **Повод для обсуждения** (15 баллов): "Спорное решение", "Разные мнения"
- **Личная связь** (10 баллов): "Это касается каждого", "Может случиться с вами"
- **Эмоциональный отклик** (5 баллов): "Вызывает сильные чувства"

## 🚫 СТРОГО ИСКЛЮЧАТЬ:

### **НЕ ПУБЛИКОВАТЬ (0-59 баллов):**
- Общие фразы без конкретики: "В Испании происходит", "Ситуация развивается"
- Новости без практической пользы: "Что-то изменилось", "Планируется сделать"
- Устаревшие новости: События старше 48 часов (кроме аналитики)
- Дублирующий контент: Похожие новости уже публиковались
- Нерелевантные темы: Слабо связанные с миграцией, жизнью в Испании
- Обычные погодные явления: "Прошел дождь", "Солнечно"
- Общие статистические данные без контекста

### **КРАТКАЯ ЗАМЕТКА (60-79 баллов):**
- Интересные, но не критичные новости
- Культурные события в приоритетных регионах
- Открытие новых заведений/услуг для русскоязычных

### **ПОЛНАЯ СТАТЬЯ + TELEGRAM (80-100 баллов):**
- Критически важные изменения в законах/документах
- Шокирующие новости с практическими последствиями
- События, которые затронут многих мигрантов
- Уникальные возможности для ЦА

## 🎨 ФОРМАТ ОЦЕНКИ:

### **СТРУКТУРА АНАЛИЗА:**
1. **📍 Региональная релевантность**: X/10 баллов
2. **😱 Удивление и эмоции**: X/25 баллов
3. **💡 Важность информации**: X/35 баллов
4. **🚀 Виральность и делительность**: X/30 баллов
5. **📊 ИТОГО**: X/100 баллов
6. **🎯 РЕКОМЕНДАЦИЯ**: [ПУБЛИКОВАТЬ/КРАТКАЯ ЗАМЕТКА/НЕ ПУБЛИКОВАТЬ]
7. **💭 ОБОСНОВАНИЕ**: Краткое объяснение решения

## 🚀 ФИНАЛЬНОЕ НАПУТСТВИЕ:

**ТЫ ОЦЕНИВАЕШЬ НОВОСТЬ С ТОЧКИ ЗРЕНИЯ ИНТЕРЕСОВ РУССКОЯЗЫЧНЫХ МИГРАНТОВ!**

- Думай как мигрант: "Как это повлияет на МОЮ жизнь?"
- Оценивай практическую пользу: "Что я могу с этим сделать?"
- Учитывай региональные особенности: "Важно ли это для МОЕГО региона?"
- Предсказывай реакцию: "Захочу ли я поделиться этой новостью?"

**НАЧИНАЙ ОЦЕНИВАТЬ СЕЙЧАС!** 🎯

---

**ИСХОДНЫЙ МАТЕРИАЛ:**
Title: {title}
Description: {description}
Tags: {tags}
Content: {content}
Source: {source}
Publication Date: {pub_date}

**ТВОЯ ЗАДАЧА:**
Оценить новость по системе 0-100 баллов и дать рекомендацию по публикации, учитывая интересы русскоязычных мигрантов в Испании и региональные приоритеты.

**ВАЖНО:** Будь строгим! Лучше не опубликовать скучную новость, чем потерять интерес читателей!"""

def get_news_filter_prompt(title, description, tags, content, source, pub_date):
    """Возвращает промпт для фильтрации новостей"""
    return NEWS_FILTER_PROMPT.format(
        title=title,
        description=description,
        tags=tags,
        content=content,
        source=source,
        pub_date=pub_date
    )

def validate_news_interest(news_data):
    """
    Валидирует новость по критериям интереса для ЦА
    """
    # Базовые проверки
    title = news_data.get('title', '')
    description = news_data.get('description', '')
    content = news_data.get('content', '')
    tags = news_data.get('tags', [])
    source = news_data.get('source', '')
    pub_date = news_data.get('pub_date', '')
    
    # Проверяем региональную релевантность
    priority_regions = ['мадрид', 'madrid', 'барселона', 'barcelona', 'bcn']
    high_priority_regions = ['малага', 'malaga', 'валенсия', 'valencia', 'аликанте', 'alicante']
    medium_priority_regions = ['марбейя', 'marbella', 'коста дель соль', 'costa del sol']
    
    # Проверяем во всех полях
    all_text = f"{title} {description} {' '.join(tags)} {content}".lower()
    
    has_priority_region = any(region in all_text for region in priority_regions)
    has_high_priority_region = any(region in all_text for region in high_priority_regions)
    has_medium_priority_region = any(region in all_text for region in medium_priority_regions)
    
    # Проверяем практическую пользу
    practical_keywords = ['документы', 'внж', 'паспорт', 'виза', 'разрешение', 'закон', 'правила', 'процедура', 'стоимость', 'цена', 'налог', 'работа', 'бизнес', 'жилье', 'аренда', 'покупка', 'приложение', 'система', 'изменения', 'новые правила', 'детский сад', 'образование', 'русский язык', 'русскоязычные', 'семьи', 'семей']
    has_practical_value = any(keyword in all_text for keyword in practical_keywords)
    
    # Проверяем срочность
    urgency_keywords = ['срочно', 'немедленно', 'сегодня', 'завтра', 'на этой неделе', 'в течение', 'срок', 'дедлайн', '1 сентября', 'с 1 сентября']
    has_urgency = any(keyword in all_text for keyword in urgency_keywords)
    
    # Проверяем масштаб
    scale_keywords = ['тысяч', 'миллион', 'все', 'каждый', 'многие', 'большинство', 'система', 'вся', 'весь', '30%', 'треть', 'треть всех']
    has_scale = any(keyword in all_text for keyword in scale_keywords)
    
    # Проверяем эмоциональность
    emotional_keywords = ['шок', 'драма', 'трагедия', 'кризис', 'катастрофа', 'сенсация', 'скандал', 'победа', 'успех', 'праздник', 'шокирующая', 'закрыли', 'закрытие', 'приятная новость', 'открылся', 'открытие', 'новый']
    has_emotions = any(keyword in all_text for keyword in emotional_keywords)
    
    # Проверяем виральность
    viral_keywords = ['спорно', 'противоречиво', 'разные мнения', 'обсуждение', 'дебаты', 'критика', 'поддержка', 'ужесточение', 'новые правила']
    has_viral_potential = any(keyword in all_text for keyword in viral_keywords)
    
    # Оценка по критериям
    regional_score = 0
    if has_priority_region:
        regional_score = 10
    elif has_high_priority_region:
        regional_score = 8
    elif has_medium_priority_region:
        regional_score = 6
    else:
        regional_score = 3
    
    surprise_score = 0
    if has_emotions:
        surprise_score += 15
    if has_viral_potential:
        surprise_score += 10
    
    importance_score = 0
    if has_practical_value:
        importance_score += 20
    if has_urgency:
        importance_score += 10
    if has_scale:
        importance_score += 5
    
    viral_score = 0
    if has_viral_potential:
        viral_score += 20
    if has_practical_value:
        viral_score += 10
    
    total_score = regional_score + surprise_score + importance_score + viral_score
    
    # Определяем рекомендацию
    if total_score >= 80:
        recommendation = "ПУБЛИКОВАТЬ"
        level = "высокий интерес"
    elif total_score >= 60:
        recommendation = "КРАТКАЯ ЗАМЕТКА"
        level = "средний интерес"
    else:
        recommendation = "НЕ ПУБЛИКОВАТЬ"
        level = "низкий интерес"
    
    return {
        'total_score': total_score,
        'regional_score': regional_score,
        'surprise_score': surprise_score,
        'importance_score': importance_score,
        'viral_score': viral_score,
        'recommendation': recommendation,
        'level': level,
        'analysis': {
            'has_priority_region': has_priority_region,
            'has_high_priority_region': has_high_priority_region,
            'has_medium_priority_region': has_medium_priority_region,
            'has_practical_value': has_practical_value,
            'has_urgency': has_urgency,
            'has_scale': has_scale,
            'has_emotions': has_emotions,
            'has_viral_potential': has_viral_potential
        }
    }

